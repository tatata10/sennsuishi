def update_all_explanations():
    files = glob.glob('../assets/questions/scraped_*.json')
    if not files:
        # Fallback for current working directory if run from scripts/
        files = glob.glob('assets/questions/scraped_*.json')
    
    if not files:
        # Try parent dir
        files = glob.glob('../assets/questions/scraped_*.json')
        
    for filename in files:
        with open(filename, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        exam_id = data.get('id', 'unknown')
        updated_count = 0
        
        for q in data['questions']:
            # Get Q ID
            no_str = str(q.get('no', '0'))
            match = re.search(r'\d+', no_str)
            q_no = match.group(0) if match else "0"
            q_id = f"{exam_id}_{q_no}"
            
            # If specifically defined in our list, use it
            if q_id in EXPLANATIONS_KV:
                q['explanation'] = EXPLANATIONS_KV[q_id]
                updated_count += 1
            # Get first category safely
            cats = q.get('categories', [])
            first_cat = cats[0] if cats else 'その他'
            
            # Otherwise if empty, generate a generic one
            if not q.get('explanation') or q.get('explanation') == "":
                q['explanation'] = generate_generic_explanation(
                    q.get('question', ''), 
                    first_cat, 
                    q.get('answer_index', 0)
                )
                updated_count += 1
                
        with open(filename, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"File {filename}: Updated {updated_count} explanations.")

if __name__ == "__main__":
    update_all_explanations()
